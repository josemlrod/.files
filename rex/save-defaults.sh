#!/bin/bash
# Reads Rex's current appearance settings from macOS preferences and rewrites
# defaults.sh with them. Run it after changing the theme, font, or layout in
# Rex's settings, then commit defaults.sh.
set -euo pipefail

domain="${REX_DEFAULTS_DOMAIN:-com.superlogical.rex}"
out="$(cd "$(dirname "$0")" && pwd)/defaults.sh"

keys=(
  Workspace.darkThemeID
  Workspace.lightThemeID
  Workspace.terminalFontName
  Workspace.terminalFontPointSize
  Workspace.interfaceStyle
  Workspace.tabStyle
  Workspace.tabIconTintMode
  Workspace.sidebarPosition
  Workspace.sidebarShowsActivity
  Workspace.paneDensity
  Workspace.inactivePaneFadeMode
  Workspace.usesStandardInactiveWindowPaneStyles
  Workspace.animationStyle
)

lines=()
for key in "${keys[@]}"; do
  if ! type=$(defaults read-type "$domain" "$key" 2>/dev/null); then
    echo "skipping $key: not set" >&2
    continue
  fi
  value=$(defaults read "$domain" "$key")
  case "${type#Type is }" in
    string)  flag=-string ;;
    float)   flag=-float ;;
    integer) flag=-int ;;
    boolean) flag=-bool; [ "$value" = 1 ] && value=true || value=false ;;
    *) echo "skipping $key: unsupported ${type}" >&2; continue ;;
  esac
  lines+=("$(printf 'defaults write "$domain" %q %s %q' "$key" "$flag" "$value")")
done

{
  echo '#!/bin/bash'
  echo '# Rex appearance settings. Generated by save-defaults.sh, so edit Rex'"'"'s'
  echo '# settings and rerun that script instead of editing this file.'
  echo '# Quit Rex before running this, then reopen it.'
  echo 'set -euo pipefail'
  echo 'domain="${REX_DEFAULTS_DOMAIN:-com.superlogical.rex}"'
  echo
  printf '%s\n' "${lines[@]}"
} > "$out"
chmod +x "$out"
echo "wrote ${#lines[@]} settings to $out"
